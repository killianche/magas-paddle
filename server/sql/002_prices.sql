-- Настоящие цены клуба вместо заглушек.
--
-- До этого была схема «днём дешевле, вечером дороже» — придуманная нами.
-- Клуб сообщил другое правило: основная цена 2500 ₽ за час, а утро до 13:00
-- стоит 2000 ₽. Поэтому колонки переименованы: тариф зависит не от «вечера»,
-- а от того, кончилось утро или нет.
--
-- Цены хранятся в копейках.

ALTER TABLE courts RENAME COLUMN price_day     TO price_morning;
ALTER TABLE courts RENAME COLUMN price_evening TO price_standard;

-- Падел-корты: цены от клуба.
UPDATE courts SET price_morning = 200000, price_standard = 250000
WHERE is_football = false;

